#!/usr/bin/env python3
"""Every row of ledger.md and ledger-1..5.md as ledger.json, for the Mac app and the site.

python3 scripts/ledger-json.py          write ledger.json
python3 scripts/ledger-json.py --check  exit 1 if ledger.json is stale
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = [f'ledger-{i}.md' for i in range(1, 6)] + ['ledger.md']

IDS = [  # kind, pattern, link
    ('oeis', r'\bA\d{6}\b', 'https://oeis.org/{}'),
    ('nct', r'\bNCT\d{8}\b', 'https://clinicaltrials.gov/study/{}'),
    ('pmc', r'\bPMC\d{5,8}\b', 'https://pmc.ncbi.nlm.nih.gov/articles/{}/'),
    ('pmid', r'(?<=PMID )\d{6,9}\b', 'https://pubmed.ncbi.nlm.nih.gov/{}/'),
    ('doi', r'\b10\.\d{4,9}/[^\s,;)]+[^\s,;).]', 'https://doi.org/{}'),
    ('arxiv', r'(?<=arXiv )\d{4}\.\d{4,5}\b', 'https://arxiv.org/abs/{}'),
]


def kind(level):
    """One of six claim classes, from the ledger's own words. The full wording stays in 'level'."""
    l = level.lower()
    if 'machine-checked' in l or 'lean' in l and 'proved' in l:
        return 'machine-checked'
    if l.startswith('written') or 'written proof' in l or 'proved' in l:
        return 'written'
    if 'candidate' in l:
        return 'candidate'
    if l.startswith(('literature', 'reproduced')):
        return 'literature'
    if l.startswith(('observed', 'computed', 'machine-decided', 'exact')):
        return 'observed'
    return 'note'


def title(claim):
    """The claim's first sentence, cut at a word near 110 characters."""
    first = re.split(r'(?<=[a-z0-9)])\. (?=[A-Z])', claim, maxsplit=1)[0].rstrip('.')
    if len(first) <= 110:
        return first
    return first[:110].rsplit(' ', 1)[0].rstrip(',;:') + '…'


def ids(text):
    seen, out = set(), []
    for k, pat, link in IDS:
        for m in re.finditer(pat, text):
            v = m.group(0)
            if v not in seen:
                seen.add(v)
                out.append({'kind': k, 'id': v, 'url': link.format(v)})
    return out


def rows():
    out = []
    for name in FILES:
        for line in (ROOT / name).read_text().splitlines():
            if not re.match(r'\| 20\d\d-\d\d-\d\d \|', line):
                continue
            cells = [c.strip() for c in line.strip().strip('|').split(' | ')]
            date, lane, claim, level, *mid = cells
            status = mid.pop() if mid else ''
            check, lit = (mid + ['', ''])[:2]
            out.append({'date': date, 'lane': lane, 'title': title(claim), 'claim': claim, 'level': level,
                        'kind': kind(level), 'check': check, 'literature': lit, 'status': status,
                        'ids': ids(' '.join(cells)), 'file': name})
    out.sort(key=lambda r: r['date'], reverse=True)  # stable: same-day rows keep ledger order
    seen = {}
    for r in out:
        base = f"{r['date']}-{r['lane']}"
        seen[base] = seen.get(base, 0) + 1
        r['id'] = f'{base}-{seen[base]}'
    return out


def build():
    r = rows()
    return {'about': 'Every row of the Noema ledger (ledger.md and ledger-1 to ledger-5), newest first. '
                     'Generated by scripts/ledger-json.py; edit the ledger, never this file.',
            'count': len(r), 'rows': r}


if __name__ == '__main__':
    text = json.dumps(build(), indent=1, ensure_ascii=False) + '\n'
    path = ROOT / 'ledger.json'
    if '--check' in sys.argv:
        sys.exit(0 if path.exists() and path.read_text() == text else 'ledger.json is stale: run scripts/ledger-json.py')
    path.write_text(text)
    print(f'{len(build()["rows"])} rows -> ledger.json')
